export function translateText(
  text: string,
  targetLang: string = 'en',
  sourceLang: string = 'en'
): TranslationResponse {
  const target = targetLang.toLowerCase();
  const trimmed = text.trim();

  if (target === 'en' || !trimmed) {
    return {
      original_text: text,
      translated_text: text,
      target_lang: target,
    };
  }

  // Check direct dictionary lookup
  if (TRANSLATION_DICTIONARY[trimmed] && TRANSLATION_DICTIONARY[trimmed][target]) {
    return {
      original_text: text,
      translated_text: TRANSLATION_DICTIONARY[trimmed][target],
      target_lang: target,
    };
  }

  // Word-by-word fallback strategy for custom text
  const words = trimmed.split(/\s+/);
  const translatedWords = words.map((word) => {
    const cleanWord = word.replace(/^[^\w\s]+|[^\w\s]+$/g, '');
    if (cleanWord && TRANSLATION_DICTIONARY[cleanWord] && TRANSLATION_DICTIONARY[cleanWord][target]) {
      return word.replace(cleanWord, TRANSLATION_DICTIONARY[cleanWord][target]);
    }
    return word;
  });

  return {
    original_text: text,
    translated_text: translatedWords.join(' '),
    target_lang: target,
  };
}
